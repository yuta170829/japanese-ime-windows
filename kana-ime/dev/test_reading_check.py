# 語幹 (送り仮名の前で切れた形)。完成した読みでも通る
STEM_ACCEPT = [
    ("あめがふ", "雨が降"),
    ("あたらしいなかまとのであ", "新しい仲間との出会"),
    ("あついほんをよ", "熱い本を読"),
    ("あいてのほうがさきにはんだんをくだ", "相手の方が先に判断を下"),
]
# 打ちかけ (partial=True のときだけ通る): 最後の語の読みが途中まで
PARTIAL_ACCEPT = [
    ("あんけーとをそそくさときにゅ", "アンケートをそそくさと記入"),
    ("あんぜんほしょうじょうじゅうよ", "安全保障上重要"),
    ("いがいなひとがたすけてくれてうれしいいっ", "意外な人が助けてくれて嬉しい一"),
    ("いえからかいしゃまでのじか", "家から会社までの時間"),
]
# 打ちかけでも通してはいけない (幻覚・繰り返し・途中でない食い違い)
PARTIAL_REJECT = [
    ("あめ", "アメアメアメ"),                                   # 繰り返し
    ("あんぜんほしょ", "安全保障保障保障保障保障保障保障安全保"),  # 繰り返し
    ("あんぜんほし", "安全⭐"),                                  # 絵文字
    ("いちおういまはしごとじかんちゅ", "一応今は仕事時間😑"),    # 絵文字
    ("あしたれい", "明日〇"),                                     # 記号
    ("きょうはがっこうにい", "今日は会社に行"),                  # 途中ではなく別の語
    ("きょうは", "今日はそして明日も"),                           # 読みに無い文字が続く
]

fails = 0
for reading, text in STEM_ACCEPT:
    if not matches(text, reading):
        fails += 1
        print("NG stem", ascii(reading), ascii(text))
for reading, text in PARTIAL_ACCEPT:
    if matches(text, reading):            # 完成した読みとしては通らないのが正しい
        fails += 1
        print("NG strict-should-reject", ascii(reading), ascii(text))
    if not matches(text, reading, partial=True):
        fails += 1
        print("NG partial-accept", ascii(reading), ascii(text))
for reading, text in PARTIAL_REJECT:
    if matches(text, reading, partial=True):
        fails += 1
        print("NG partial-reject", ascii(reading), ascii(text))
for reading, text in ACCEPT:
    if not matches(text, reading):
        fails += 1
        print("NG accept", ascii(reading), ascii(text))
for reading, text in REJECT:
    if matches(text, reading):
        fails += 1
        print("NG reject", ascii(reading), ascii(text))
total = (len(ACCEPT) + len(REJECT) + len(STEM_ACCEPT)
         + 2 * len(PARTIAL_ACCEPT) + len(PARTIAL_REJECT))
print(f"{total - fails}/{total}")
sys.exit(1 if fails else 0)
